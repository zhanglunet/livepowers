"""PRD-130/T2：多 harness 发布矩阵实现（trend #650）。

源 SKILL.md → 各 harness 适配器转换 → 校验 → 输出。
适配器为纯文本变换（标题/路径/格式），不改语义。
"""
from __future__ import annotations
import json
from pathlib import Path
from typing import Any

MATRIX = {
    "claude-code": {"entry": "SKILL.md", "install": "skills.sh add"},
    "cursor": {"entry": ".cursorrules", "install": "manual"},
    "windsurf": {"entry": ".windsurfrules", "install": "manual"},
    "generic": {"entry": "AGENTS.md", "install": "manual"},
}

def generate_matrix(skill_name: str, skill_dir: str) -> dict[str, Any]:
    """生成发布矩阵。"""
    entry_path = Path(skill_dir) / "SKILL.md"
    if not entry_path.is_file():
        raise FileNotFoundError(f"SKILL.md 不存在：{entry_path}")
    content = entry_path.read_text(encoding="utf-8")
    results = []
    for harness, config in MATRIX.items():
        results.append({
            "harness": harness,
            "entry": config["entry"],
            "install": config["install"],
            "skill": skill_name,
            "source_length": len(content),
            "compatible": True,
        })
    return {"schema": "harness-matrix/v1", "skill": skill_name, "targets": results}


# ── PRD-130/T3+T4（trend #651/#652）：六路真生成 + 一致性校验 ─────────────
#
# 六路工具（字面口径）：Claude Code / Codex / Cursor / OpenCode / Copilot / Pi。
# 生成为纯文本变换（剥/留 frontmatter + 溯源头），语义不改；一致性校验 =
# 内存再生成与盘上产物逐字节比对（CI 口径：生成物未手改）。

import hashlib
import re

MATRIX_V2 = {
    "claude-code": {"entry": "SKILL.md", "install": "skills.sh add", "frontmatter": True},
    "codex": {"entry": "AGENTS.md", "install": "manual", "frontmatter": False},
    "cursor": {"entry": ".cursorrules", "install": "manual", "frontmatter": False},
    "opencode": {"entry": "opencode/AGENTS.md", "install": "manual", "frontmatter": False},
    "copilot": {"entry": "copilot-instructions.md", "install": "manual", "frontmatter": False},
    "pi": {"entry": "pi/SKILL.md", "install": "manual", "frontmatter": True},
}

_HEADER = ("<!-- generated by harness-matrix/v2 from skills/{skill}/SKILL.md; "
           "do not hand-edit（CI 一致性校验口径，手改即 drift） -->")

def _strip_frontmatter(content: str) -> str:
    if content.startswith("---"):
        m = re.match(r"^---\n.*?\n---\n?", content, re.S)
        if m:
            return content[m.end():].lstrip("\n")
    return content


def build_output(harness: str, skill_name: str, content: str) -> str:
    """单工具纯文本变换：frontmatter 剥/留 + 溯源头。语义不改。

    frontmatter 保留型（claude-code/pi）：SKILL.md 的 frontmatter 必须在文件头，
    溯源头插到 frontmatter 块之后；剥离型：头注释置顶。
    """
    cfg = MATRIX_V2[harness]
    header = _HEADER.format(skill=skill_name)
    if cfg["frontmatter"] and content.startswith("---"):
        m = re.match(r"^---\n.*?\n---\n?", content, re.S)
        fence_end = m.end() if m else 0
        return f"{content[:fence_end]}\n{header}\n{content[fence_end:]}"
    body = content if cfg["frontmatter"] else _strip_frontmatter(content)
    return f"{header}\n\n{body}"


def generate_outputs(skill_name: str, skill_dir: str, out_dir: str) -> dict:
    """六路真生成：写盘 + 清单（harness-matrix/v2，逐产物 sha256）。"""
    entry_path = Path(skill_dir) / "SKILL.md"
    if not entry_path.is_file():
        raise FileNotFoundError(f"SKILL.md 不存在：{entry_path}")
    content = entry_path.read_text(encoding="utf-8")
    artifacts = []
    for harness, cfg in MATRIX_V2.items():
        text = build_output(harness, skill_name, content)
        rel = cfg["entry"].format(skill=skill_name)
        target = Path(out_dir) / harness / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
        artifacts.append({
            "harness": harness, "entry": rel,
            "path": str(target), "bytes": len(text.encode("utf-8")),
            "sha256": hashlib.sha256(text.encode("utf-8")).hexdigest()[:16],
        })
    return {"schema": "harness-matrix/v2", "skill": skill_name, "artifacts": artifacts}


def verify_unmodified(skill_dir: str, out_dir: str) -> dict:
    """CI 一致性校验：内存再生成 vs 盘上产物逐字节比对；drift 逐条点名。"""
    entry_path = Path(skill_dir) / "SKILL.md"
    content = entry_path.read_text(encoding="utf-8")
    drift = []
    checked = 0
    for harness, cfg in MATRIX_V2.items():
        expected = build_output(harness, Path(skill_dir).name, content)
        target = Path(out_dir) / harness / cfg["entry"]
        if not target.is_file():
            drift.append({"harness": harness, "issue": "missing"})
            continue
        checked += 1
        if target.read_text(encoding="utf-8") != expected:
            drift.append({"harness": harness, "issue": "hand-edited"})
    return {"ok": not drift, "checked": checked, "drift": drift}
